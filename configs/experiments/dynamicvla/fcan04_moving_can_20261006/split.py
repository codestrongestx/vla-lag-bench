"""Split the ribbed 200-episode bank into a random-20 pilot and its 180 complement.

Run from the repository root:

    uv run python configs/experiments/dynamicvla/fcan04_moving_can_20261006/split.py

Selection follows the food-can random-20 pilot
(configs/studies/fcan04_native_pilot20_20260928/README.md): sample 20 box
placements without replacement from range(50), then shuffle
[0, 50, 100, 150] * 5 and add those offsets, so each phase-half/direction
block contributes five pilot episodes. Every selected bank episode keeps its
box placement, start phase and direction; local state indices are remapped
to the subset's episode order.
"""
from __future__ import annotations

import copy
import json
import random
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
BANK = HERE / "ribbed-experiment.yaml"
SEED = 20261008
STATES = 50
BLOCKS = 4
PILOT = 20


def subset(bank: dict, name: str, episodes: list[int]) -> dict:
    """Bank episodes as an experiment with one local state per episode."""

    states = bank["benchmark"]["initial_states_per_environment"]
    boxes = {o["initial_state_index"]: o for o in bank["initial_state_overrides"]}
    document = copy.deepcopy(bank)
    document["name"] = name
    document["benchmark"]["episodes_per_environment"] = len(episodes)
    document["benchmark"]["initial_states_per_environment"] = len(episodes)
    document["initial_state_overrides"] = [
        {**copy.deepcopy(boxes[episode % states]), "initial_state_index": local}
        for local, episode in enumerate(episodes)
    ]
    schedule = bank["trajectory"]["episode_schedule"]
    document["trajectory"]["episode_schedule"] = [schedule[episode] for episode in episodes]
    return document


def main() -> None:
    bank = yaml.safe_load(BANK.read_text())
    assert bank["benchmark"]["initial_states_per_environment"] == STATES
    assert bank["benchmark"]["episodes_per_environment"] == STATES * BLOCKS

    rng = random.Random(SEED)
    placements = rng.sample(range(STATES), PILOT)
    offsets = [block * STATES for block in range(BLOCKS)] * (PILOT // BLOCKS)
    rng.shuffle(offsets)
    pilot = [placement + offset for placement, offset in zip(placements, offsets)]
    remaining = sorted(set(range(STATES * BLOCKS)) - set(pilot))

    for directory, name, episodes, comment in (
        ("fcan04_moving_can_pilot20_20261008", "fcan04-moving-can-ribbed-random20-750steps", pilot,
         "Stratified random 20 of the ribbed 200-episode bank"),
        ("fcan04_moving_can_remaining180_20261008", "fcan04-moving-can-ribbed-remaining180-750steps",
         remaining, "The ribbed 200-episode bank without the random-20 pilot"),
    ):
        out = ROOT / "configs/studies" / directory
        out.mkdir(parents=True, exist_ok=True)
        (out / "base.yaml").write_text(
            f"# {comment}; generated by\n"
            "# configs/experiments/dynamicvla/fcan04_moving_can_20261006/split.py.\n"
            + yaml.safe_dump(subset(bank, name, episodes), sort_keys=False))
        (out / "selection.json").write_text(json.dumps({
            "source": "configs/experiments/dynamicvla/fcan04_moving_can_20261006/ribbed-experiment.yaml",
            "seed": SEED,
            "pilot_source_episode_ids": pilot,
            "remaining_source_episode_ids": remaining,
        }, indent=2) + "\n")
    print(json.dumps({"pilot": pilot}))


if __name__ == "__main__":
    main()
